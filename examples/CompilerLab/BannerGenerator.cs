using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Course.CompilerLab;

[Generator]
public sealed class BannerGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidInput = new(
        "COURSE002", "Invalid course metadata",
        "Provide exactly one nonblank course.txt", "Generation",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var titles = context.AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path) == "course.txt")
            .Select((file, token) => file.GetText(token)?.ToString().Trim() ?? "")
            .Collect();
        context.RegisterSourceOutput(titles, (output, values) =>
        {
            if (values.Length != 1 || string.IsNullOrWhiteSpace(values[0]))
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidInput, Location.None));
                return;
            }
            string literal = SymbolDisplay.FormatLiteral(values[0], quote: true);
            string code = $$"""
                // <auto-generated/>
                #nullable enable
                namespace Course.Generated;
                public static partial class BuildInfo
                {
                    public static string Title => {{literal}};
                }
                """;
            output.AddSource("BuildInfo.g.cs", SourceText.From(code, Encoding.UTF8));
        });
    }
}
